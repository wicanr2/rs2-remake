//! 工具列與提示文字用的點陣字型。ASCII 大寫字母、數字與少數符號，5×7 格，由本專案自繪。
//! 不使用 BIOS 或任何既有字型的點陣資料，也不需要字型檔。
//!
//! 每個字符是 7 列字串，`#` 是亮點，`.` 是空點。

