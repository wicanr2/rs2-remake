/// 取字符的 7 列位元（最高位元在左，只用低 5 位元）。不認得的字元畫成空白。小寫轉大寫。
pub fn glyph(c: char) -> [u8; GLYPH_H] {
    let c = c.to_ascii_uppercase();
    let rows = GLYPHS.iter().find(|(ch, _)| *ch == c).map(|(_, g)| g).unwrap_or(&GLYPHS[GLYPHS.len() - 1].1);
    let mut out = [0u8; GLYPH_H];
    for (r, line) in rows.iter().enumerate() {
        for (x, ch) in line.bytes().enumerate() {
            if ch == b'#' {
                out[r] |= 1 << (GLYPH_W - 1 - x);
            }
        }
    }
    out
}

/// 一段文字的寬度（像素，`scale` 倍），不含最後一個字元後面的空隙。
pub fn text_width(text: &str, scale: usize) -> usize {
    let n = text.chars().count();
    if n == 0 { 0 } else { (n * ADVANCE - (ADVANCE - GLYPH_W)) * scale }
}

pub fn text_height(scale: usize) -> usize {
    GLYPH_H * scale
}

/// 在 RGBA 緩衝區 `(x, y)` 畫文字。超出邊界的像素略過。
pub fn draw_text(buf: &mut [u8], buf_w: usize, buf_h: usize, x: i32, y: i32, text: &str, scale: usize, rgba: [u8; 4]) {
    let mut pen = x;
    for c in text.chars() {
        let g = glyph(c);
        for (r, bits) in g.iter().enumerate() {
            for col in 0..GLYPH_W {
                if bits & (1 << (GLYPH_W - 1 - col)) == 0 {
                    continue;
                }
                for dy in 0..scale as i32 {
                    for dx in 0..scale as i32 {
                        let px = pen + (col * scale) as i32 + dx;
                        let py = y + (r * scale) as i32 + dy;
                        if px < 0 || py < 0 || px as usize >= buf_w || py as usize >= buf_h {
                            continue;
                        }
                        let o = (py as usize * buf_w + px as usize) * 4;
                        buf[o..o + 4].copy_from_slice(&rgba);
                    }
                }
            }
        }
        pen += (ADVANCE * scale) as i32;
    }
}

/// 填實心矩形（RGBA，超出邊界的部分略過）。
pub fn fill_rect(buf: &mut [u8], buf_w: usize, buf_h: usize, x: i32, y: i32, w: i32, h: i32, rgba: [u8; 4]) {
    for py in y.max(0)..(y + h).min(buf_h as i32) {
        for px in x.max(0)..(x + w).min(buf_w as i32) {
            let o = (py as usize * buf_w + px as usize) * 4;
            buf[o..o + 4].copy_from_slice(&rgba);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_5_by_7() {
        for (c, g) in GLYPHS {
            assert_eq!(g.len(), GLYPH_H);
            for line in g {
                assert_eq!(line.len(), GLYPH_W, "{c}");
                assert!(line.bytes().all(|b| b == b'#' || b == b'.'), "{c}");
            }
        }
    }

    #[test]
    fn glyphs_are_distinct_and_non_blank() {
        let mut seen = std::collections::HashMap::new();
        for (c, _) in GLYPHS {
            let g = glyph(*c);
            if *c != ' ' {
                assert!(g.iter().any(|&b| b != 0), "{c} 是空的");
            }
            if let Some(prev) = seen.insert(g, *c) {
                panic!("{prev} 與 {c} 的點陣相同");
            }
        }
    }

    #[test]
    fn covers_the_toolbar_alphabet() {
        for c in "F1 TWEEN ON OFF COUNT F2 F3 HD ORIG NO F4 X2345 F10 HIDE STAGE 1 CLEAR - PRESS ENTER LOADING.".chars() {
            assert!(GLYPHS.iter().any(|(g, _)| *g == c), "缺 {c:?}");
        }
    }

    #[test]
    fn lowercase_maps_to_uppercase_and_unknown_to_blank() {
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('é'), glyph(' '));
    }

    #[test]
    fn widths() {
        assert_eq!(text_width("", 2), 0);
        assert_eq!(text_width("A", 1), 5);
        assert_eq!(text_width("AB", 1), 11);
        assert_eq!(text_width("AB", 3), 33);
        assert_eq!(text_height(2), 14);
    }

    #[test]
    fn draw_text_writes_pixels_and_clips() {
        let (w, h) = (16usize, 10usize);
        let mut buf = vec![0u8; w * h * 4];
        draw_text(&mut buf, w, h, 1, 1, "I", 1, [9, 8, 7, 255]);
        // 'I' 第一列 "#####"：x = 1..=5, y = 1。
        for x in 1..=5 {
            let o = (w + x) * 4;
            assert_eq!(&buf[o..o + 4], &[9, 8, 7, 255]);
        }
        assert_eq!(&buf[(w + 6) * 4..(w + 6) * 4 + 4], &[0, 0, 0, 0]);
        // 全部超出邊界也不 panic。
        draw_text(&mut buf, w, h, -100, -100, "ABC", 3, [1, 1, 1, 1]);
        draw_text(&mut buf, w, h, 100, 100, "ABC", 3, [1, 1, 1, 1]);
    }
}
